-- ============================================================
-- 選択肢の「価格カード」表示フラグ
--
--   ラジオ／チェックボックスの選択肢を、小さなラジオのリストではなく
--   タップしやすい「価格カード」で見せる（申込フォームのコース選択向け）。
--   true のときカード表示。選択肢ラベルの「｜」（全角）または「|」以降を
--   価格・補足として分けて表示する（例：AI会社 構築コース｜¥605,000）。
--
--   ⚠️ 既存データは false（従来どおりリスト表示）。
--
--   適用: Supabase コンソール → SQL Editor に貼り付けて実行（何度実行しても安全）
-- ============================================================

alter table public.form_fields
  add column if not exists option_cards boolean not null default false;

comment on column public.form_fields.option_cards is
  '選択肢を価格カードで表示するか（true=カード／false=リスト）。ラジオ・チェックで有効。';
