-- ============================================================
-- 件数の再集計（冪等）
--   取込・削除の直後と夜間バッチから呼ぶ。いつ呼んでも実体と一致する。
-- ============================================================
create or replace function public.recount_contact_list(p_list_id bigint)
returns void
language sql
security definer
set search_path = public
as $$
  update contact_lists c set
    entry_count      = (select count(*) from contact_list_entries e where e.list_id = c.id),
    emailable_count  = (select count(*) from contact_list_entries e where e.list_id = c.id and e.email_norm is not null),
    phone_only_count = (select count(*) from contact_list_entries e where e.list_id = c.id and e.email_norm is null),
    updated_at       = now()
  -- ⚠️ security definer は RLS を迂回するので、運営判定を関数内で必ず掛ける
  where c.id = p_list_id and public.is_ops();
$$;
grant execute on function public.recount_contact_list(bigint) to authenticated;

comment on function public.recount_contact_list(bigint) is
  'リストの件数キャッシュを実体から再集計する（冪等）';

-- ============================================================
-- 並べ替え（手動）
--   受け取った id 配列の順に sort_order を 10 刻みで振り直す。
--   ⚠️ 配列に含まれないリストは触らない（検索で絞った状態からの誤爆を防ぐ）。
-- ============================================================
create or replace function public.reorder_contact_lists(p_ids bigint[])
returns void
language sql
security definer
set search_path = public
as $$
  -- ⚠️ 順序の保証は with ordinality で行う（row_number() over () は順序を保証しない）
  update contact_lists c
     set sort_order = (t.ord * 10)::int,
         updated_at = now()
    from unnest(p_ids) with ordinality as t(id, ord)
   where c.id = t.id and public.is_ops();
$$;
grant execute on function public.reorder_contact_lists(bigint[]) to authenticated;

comment on function public.reorder_contact_lists(bigint[]) is
  'リストの手動並べ替え。渡された順に sort_order を10刻みで振り直す';

