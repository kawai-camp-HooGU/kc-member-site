-- ============================================================
-- リスト管理（配信先リスト）
--   メールアドレス・電話番号を「リスト」として登録・管理し、
--   一斉配信／シナリオ配信の配信先として使えるようにする。
--
--   contact_lists           … リスト枠（画面の左ペイン）
--   contact_list_imports    … 一括取込ジョブ（Phase 2 で使用。先に器だけ作る）
--   contact_list_entries    … レコード（画面の右ペイン）
--   contact_list_deliveries … 配信で使われた履歴（送信時点のスナップショット）
--
--   設計方針（preview/設計書/2026-08-17_リスト管理機能_設計書.html rev.2）
--     ・重複判定は「ファイル内」と「同一リスト内」のみ。他リストは照合しない
--     ・生の入力値（表示用）と正規化値（重複判定用）を別カラムで持つ
--     ・会員に依存しない独立エンティティ（member_id は nullable）
--     ・並び順は手動（sort_order を 10 刻みで採番）
--     ・削除はアーカイブ（論理削除）のみ。物理削除はしない
--
--   ⚠️ すべて運営専用（RLS = is_ops()）。会員クライアントからは触らせない。
--   ⚠️ 何度実行しても安全（if not exists）。
-- ============================================================

-- ── リスト枠 ────────────────────────────────────────────────
create table if not exists public.contact_lists (
  id               bigint generated by default as identity primary key,
  name             text        not null,
  description      text        not null default '',
  note1            text        not null default '',
  note2            text        not null default '',
  folder_id        bigint      references public.folders(id) on delete set null,
  -- 件数の非正規化キャッシュ。recount_contact_list() で冪等に復元できる
  entry_count      int         not null default 0,
  emailable_count  int         not null default 0,   -- メール送信できる件数
  phone_only_count int         not null default 0,   -- 電話のみ（メール配信不可）
  -- 手動並べ替え。10 刻みで採番し、挿入は前後の中間値を使う（昇順で表示）
  sort_order       int         not null default 0,
  allow_delivery   boolean     not null default true,  -- 配信先として選べるか
  consent_note     text        not null default '',    -- 取得元・同意メモ（特定電子メール法の記録用）
  is_archived      boolean     not null default false, -- アーカイブ（宛先に選べない／履歴は残る）
  is_deleted       boolean     not null default false, -- 論理削除（マスタ方針に合わせる）
  created_by       uuid,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

-- 既定の並び＝手動（sort_order）。同値は更新の新しい順で安定させる
create index if not exists idx_contact_lists_order
  on public.contact_lists(sort_order, updated_at desc) where is_deleted = false;

comment on table  public.contact_lists              is 'リスト枠（配信先リスト）。レコードは contact_list_entries';
comment on column public.contact_lists.sort_order   is '手動並べ替えの位置（10刻み）。昇順で表示。同値は updated_at desc';
comment on column public.contact_lists.is_archived  is 'アーカイブ。配信先には選べないが配信履歴の参照用に残す';
comment on column public.contact_lists.consent_note is '取得元・同意メモ。特定電子メール法の同意記録（リスト単位）';
comment on column public.contact_lists.entry_count  is '件数キャッシュ。recount_contact_list() で再集計できる';

-- ── 取込ジョブ（Phase 2 で使用。entries が参照するため先に作る）──────
create table if not exists public.contact_list_imports (
  id              bigint generated by default as identity primary key,
  list_id         bigint      not null references public.contact_lists(id) on delete cascade,
  file_name       text        not null default '',
  file_kind       text        not null default 'csv',    -- 'csv' | 'paste'（'md' は Phase 5）
  encoding        text        not null default 'utf-8',  -- 'utf-8' | 'utf-8-bom' | 'cp932'
  delimiter       text        not null default ',',
  column_map      jsonb       not null default '{}'::jsonb,
  dup_policy      text        not null default 'skip',   -- 'skip' | 'update' | 'abort'
  blank_overwrite boolean     not null default false,    -- 空欄で既存値を上書きするか（既定オフ）
  skip_suppressed boolean     not null default true,     -- 配信停止リストのアドレスを除外するか
  total_rows      int         not null default 0,
  inserted        int         not null default 0,
  updated         int         not null default 0,
  skipped         int         not null default 0,
  failed          int         not null default 0,
  error_rows      jsonb       not null default '[]'::jsonb, -- 失敗行CSVの生成元（30日で消す）
  status          text        not null default 'queued',   -- queued|running|done|failed|canceled
  error_message   text,
  created_by      uuid,
  started_at      timestamptz,
  finished_at     timestamptz,
  created_at      timestamptz not null default now()
);
create index if not exists idx_contact_imports_list
  on public.contact_list_imports(list_id, id desc);

comment on table  public.contact_list_imports            is 'リストの一括取込ジョブ。非同期実行の進捗と結果を保持';
comment on column public.contact_list_imports.error_rows is '失敗行（元の値＋失敗理由）。失敗CSVのダウンロード元。30日で消す';

-- ── レコード ────────────────────────────────────────────────
create table if not exists public.contact_list_entries (
  id          bigint generated by default as identity primary key,
  list_id     bigint      not null references public.contact_lists(id) on delete cascade,
  -- 会員（members）に紐づいたら入る。非会員の生アドレスは null のまま
  member_id   bigint      references public.members(id) on delete set null,
  matched_by  text,                                    -- 'member_id' | 'email' | null
  -- 生の入力値（表示用）と正規化値（重複判定用）を必ず分ける
  --   ⚠️ 正規化はアプリ側（lib/contactLists.ts）で行う。生成列にしない
  --      （Gmail 限定のドット除去ロジックを2箇所に分散させないため）
  email       text,
  email_norm  text,
  phone       text,
  phone_e164  text,
  name        text        not null default '',
  age_group   text,                                    -- '10代'…'80代以上' | '不明'
  prefecture  text,
  note1       text        not null default '',
  note2       text        not null default '',
  source_kind text        not null default 'manual',   -- 'manual' | 'csv'（'md'|'api' は将来）
  import_id   bigint      references public.contact_list_imports(id) on delete set null,
  consent_at  timestamptz,                             -- 同意日時（レコード単位・任意）
  consent_src text,                                    -- 同意の取得元
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  -- 要件：メールアドレス・電話番号のどちらか一方は必須
  --   ⚠️ 正規化後の列に掛ける。生 email だけ入って email_norm が null（＝形式不正）の
  --      レコードを作らせないため
  constraint entry_contact_required
    check (email_norm is not null or phone_e164 is not null)
);

-- 同一リスト内の重複防止（部分UNIQUE。scenario_entries_email_uk と同じ流儀）
create unique index if not exists contact_entries_email_uk
  on public.contact_list_entries (list_id, email_norm) where email_norm is not null;
create unique index if not exists contact_entries_phone_uk
  on public.contact_list_entries (list_id, phone_e164) where phone_e164 is not null;
-- 会員名寄せ・配信時の突合用
create index if not exists idx_contact_entries_email_norm on public.contact_list_entries(email_norm);
create index if not exists idx_contact_entries_member     on public.contact_list_entries(member_id);
-- keyset ページング用（OFFSET を使わない）
create index if not exists idx_contact_entries_list_id    on public.contact_list_entries(list_id, id desc);

comment on table  public.contact_list_entries             is 'リストのレコード（連絡先）。メール・電話のどちらか一方が必須';
comment on column public.contact_list_entries.email_norm  is '重複判定用の正規化メール。小文字化＋Gmail系のみドット/+タグ除去';
comment on column public.contact_list_entries.phone_e164  is '重複判定用の正規化電話（E.164）。既定国は日本（+81）';
comment on column public.contact_list_entries.member_id   is '会員と紐づいた場合の members.id。非会員は null';
comment on column public.contact_list_entries.matched_by  is '紐づけの根拠：member_id=ID一致 / email=正規化メールでの名寄せ';

-- ── 配信履歴（送信時点のスナップショット）────────────────────
create table if not exists public.contact_list_deliveries (
  id                 bigint generated by default as identity primary key,
  list_id            bigint      not null references public.contact_lists(id) on delete cascade,
  kind               text        not null,             -- 'broadcast' | 'scenario'
  broadcast_id       bigint      references public.broadcasts(id) on delete set null,
  scenario_id        bigint      references public.scenarios(id)  on delete set null,
  -- ↓ 後からリストや配信を編集・改名・削除しても履歴が壊れないための写し
  list_name_snapshot text        not null default '',
  title_snapshot     text        not null default '',
  channel            text        not null default 'email',
  target_count       int         not null default 0,    -- 送信時点のリスト件数
  sent_count         int         not null default 0,
  excluded_count     int         not null default 0,
  -- {suppressed:12, phone_only:24, invalid:2, dup:3}
  excluded_breakdown jsonb       not null default '{}'::jsonb,
  sent_at            timestamptz not null default now()
);
create index if not exists idx_contact_deliv_list
  on public.contact_list_deliveries(list_id, sent_at desc);

comment on table public.contact_list_deliveries is
  'リストを宛先に使った配信の履歴。件数・リスト名は送信時点のスナップショット';

