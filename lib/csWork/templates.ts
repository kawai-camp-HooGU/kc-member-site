/** 種別ごとのテンプレート本文とファイル名 */
export function templateFor(kind: CsWorkKind): { filename: string; content: string } {
  if (kind === "watchlist") return { filename: "要監視顧客一覧_テンプレート.csv", content: WATCHLIST_TEMPLATE };
  if (kind === "design")    return { filename: "CS運用_AI作業設計_テンプレート.md", content: DESIGN_TEMPLATE };
  return { filename: "CS運用_導線種別_テンプレート.md", content: OPS_TEMPLATE };
}
